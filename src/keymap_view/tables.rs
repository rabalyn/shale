//! The two fixed tables of the keymap view (KEY-055): the keys that are not in the key registry
//! (text editing, the editor, vim-lite normal mode, the drawing tools, egui's zoom and quit: `BUILTIN`)
//! and the keys the systems reserve (`RESERVED_*`, the tables behind KEY-019 and its research), plus the
//! short names of the actions for the chips on the keys. They are plain data, so a later export (as JSON,
//! for a web page, rabalyn/shale#712) reads them as they are.
//!
//! A chord is written like the keys of the registry (`Ctrl+Shift+K`) with `Super` for the key that
//! is Win on Windows, Super on Linux and Control on macOS (`Ctrl` is Cmd on macOS).
// Generated once from the research page of the keyboard (rabalyn/shale#710); edit by hand from now on.

use super::model::{Category, Where};

/// A key that is fixed in the program and cannot be given to an action.
pub struct Builtin {
    pub keys: &'static str,
    /// On which systems it works: `l` Linux, `w` Windows, `m` macOS.
    pub systems: &'static str,
    pub label: &'static str,
    pub scope: Where,
    pub cat: Category,
    /// A remark for the detail panel, empty for none.
    pub note: &'static str,
}

/// How a reserved entry matches a key.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Match {
    /// Exactly this chord.
    Exact,
    /// Every chord that holds these modifiers (a Super key: the desktop takes them all).
    AnyKeyWith,
    /// Every chord with these modifiers and a key that types a character (AltGr is Ctrl+Alt on Windows).
    AnyCharWith,
}

/// A key (or a family of keys) a system keeps for itself.
pub struct Reserved {
    /// The chord, or for the two families only the modifiers (`Super`, `Ctrl+Alt`).
    pub keys: &'static str,
    pub label: &'static str,
    pub kind: Match,
}

